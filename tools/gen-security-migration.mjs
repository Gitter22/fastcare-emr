#!/usr/bin/env node
// Generates the security migration from prisma/schema.prisma doc tags (docs/ehr-spec/docs/09-data-model.md):
//   @tenant       -> ENABLE ROW LEVEL SECURITY + tenant_isolation policy on app.practice_id (INV-SEC-02)
//   @append-only  -> app_api gets SELECT, INSERT only (INV-SEC-01, INV-FIN-01)
// Usage: node tools/gen-security-migration.mjs > prisma/migrations/<ts>_security/migration.sql
//
// RLS is ENABLEd but not FORCEd: the migration/owner role must still be able to seed and serve the
// SECURITY DEFINER login lookups (same lesson as agile-emr's 20260811123000_no_force_rls_for_table_owner).
// The running API connects as app_api (APP_DATABASE_URL), which is not the owner and has no BYPASSRLS.
import { readFileSync } from "node:fs";

const schema = readFileSync(new URL("../prisma/schema.prisma", import.meta.url), "utf8");
const modelRe = /((?:\/\/\/.*\n)*)model (\w+) \{([\s\S]*?)\n\}/g;
const models = [];
for (const m of schema.matchAll(modelRe)) {
  const tags = m[1];
  const body = m[3];
  models.push({
    name: m[2],
    tenant: tags.includes("@tenant"),
    appendOnly: tags.includes("@append-only"),
    nullablePractice: /\n\s+practiceId\s+String\?/.test(body),
  });
}

// Append-only tables whose spec'd workflow sets a few review columns after insert. Only those columns are
// updatable; every other column stays immutable.
const appendOnlyUpdatableColumns = {
  EmergencyAccessGrant: ["reviewOutcome", "reviewedById", "reviewedAt", "reviewNote"],
  PatientMerge: ["unmergedById", "unmergedAt"],
};

// Tables whose rows legitimately exist without a tenant (pre-authentication events, network directory).
const sharedNullTenant = {
  AuditEvent: "insert-only",
  ResourceVersion: "insert-only",
  Pharmacy: "read",
};

const q = (n) => `"${n}"`;
const out = [];
out.push(`-- GENERATED by tools/gen-security-migration.mjs from prisma/schema.prisma doc tags. Do not edit by hand.
-- Tenant isolation (INV-SEC-02, ADR-009), append-only grants (INV-SEC-01, INV-FIN-01) and login lookups.

DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'app_api') THEN
    -- Development default only; production rotates it with ALTER ROLE app_api WITH PASSWORD ... (same as agile-emr).
    CREATE ROLE app_api LOGIN PASSWORD 'dev_only_app_api_password_change_in_prod'
      NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
  END IF;
END
$$;

GRANT USAGE ON SCHEMA public TO app_api;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO app_api;

-- Current tenant for the transaction; NULL when unset (fails closed: no row matches).
CREATE OR REPLACE FUNCTION app_current_practice() RETURNS uuid
  LANGUAGE sql STABLE AS $$ SELECT NULLIF(current_setting('app.practice_id', true), '')::uuid $$;
`);

for (const m of models) {
  const t = q(m.name);
  if (m.appendOnly) {
    out.push(`GRANT SELECT, INSERT ON ${t} TO app_api;`);
    const cols = appendOnlyUpdatableColumns[m.name];
    if (cols) out.push(`GRANT UPDATE (${cols.map(q).join(", ")}) ON ${t} TO app_api;`);
  } else {
    out.push(`GRANT SELECT, INSERT, UPDATE, DELETE ON ${t} TO app_api;`);
  }
  if (m.name === "OutboxEvent") {
    // Append-only except the dispatch marker (docs/09-data-model.md).
    out.push(`REVOKE UPDATE, DELETE ON ${t} FROM app_api;`);
    out.push(`GRANT UPDATE ("dispatchedAt", "attempts") ON ${t} TO app_api;`);
  }
  if (!m.tenant) continue;
  out.push(`ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`);
  const shared = sharedNullTenant[m.name];
  if (shared === "read") {
    out.push(`CREATE POLICY tenant_isolation ON ${t}
  USING ("practiceId" IS NULL OR "practiceId" = app_current_practice())
  WITH CHECK ("practiceId" = app_current_practice());`);
  } else if (shared === "insert-only") {
    // Pre-authentication events (failed logins) are written without a tenant and never read back by app_api.
    out.push(`CREATE POLICY tenant_isolation ON ${t}
  USING ("practiceId" = app_current_practice())
  WITH CHECK ("practiceId" IS NULL OR "practiceId" = app_current_practice());`);
  } else {
    out.push(`CREATE POLICY tenant_isolation ON ${t}
  USING ("practiceId" = app_current_practice())
  WITH CHECK ("practiceId" = app_current_practice());`);
  }
}

// Practice is the tenant row itself.
out.push(`ALTER TABLE "Practice" ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON "Practice" USING ("id" = app_current_practice()) WITH CHECK ("id" = app_current_practice());`);

out.push(`
-- Login lookups run before a tenant is known. SECURITY DEFINER (owner, not subject to RLS since RLS is not FORCEd)
-- and narrow: they return only what authentication needs, never an open query.
CREATE OR REPLACE FUNCTION find_staff_users_for_login(p_email text)
RETURNS TABLE (id uuid, "practiceId" uuid, "passwordHash" text, status text, "failedLoginCount" int,
               "lockedUntil" timestamptz, "mfaEnrolledAt" timestamptz, "passwordChangedAt" timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT u.id, u."practiceId", u."passwordHash", u.status::text, u."failedLoginCount", u."lockedUntil",
         u."mfaEnrolledAt", u."passwordChangedAt"
  FROM "User" u
  WHERE lower(u.email) = lower(p_email) AND u.status <> 'DEACTIVATED'
$$;
REVOKE ALL ON FUNCTION find_staff_users_for_login(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION find_staff_users_for_login(text) TO app_api;

-- Practice for a staff user id (used by refresh and MFA steps that only carry the user id).
CREATE OR REPLACE FUNCTION find_staff_user_practice(p_user_id uuid)
RETURNS uuid LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT "practiceId" FROM "User" WHERE id = p_user_id
$$;
REVOKE ALL ON FUNCTION find_staff_user_practice(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION find_staff_user_practice(uuid) TO app_api;

-- Practice for a portal patient id (portal users span practices through PortalAccess).
CREATE OR REPLACE FUNCTION find_patient_practice(p_patient_id uuid)
RETURNS uuid LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT "practiceId" FROM "Patient" WHERE id = p_patient_id
$$;
REVOKE ALL ON FUNCTION find_patient_practice(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION find_patient_practice(uuid) TO app_api;

-- Practice for an emailed account token (invite, reset, portal activation).
CREATE OR REPLACE FUNCTION find_token_practice(p_user_id uuid, p_patient_id uuid)
RETURNS uuid LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT COALESCE((SELECT "practiceId" FROM "User" WHERE id = p_user_id),
                  (SELECT "practiceId" FROM "Patient" WHERE id = p_patient_id))
$$;
REVOKE ALL ON FUNCTION find_token_practice(uuid, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION find_token_practice(uuid, uuid) TO app_api;

-- Webhook routing: the tenant that owns an integration connection.
CREATE OR REPLACE FUNCTION find_connection_practice(p_connection_id uuid)
RETURNS uuid LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT "practiceId" FROM "IntegrationConnection" WHERE id = p_connection_id
$$;
REVOKE ALL ON FUNCTION find_connection_practice(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION find_connection_practice(uuid) TO app_api;

-- Background workers iterate tenants; they then run each tenant's work under that tenant's RLS context.
CREATE OR REPLACE FUNCTION list_active_practices()
RETURNS TABLE (id uuid, timezone text) LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT id, timezone FROM "Practice" WHERE active
$$;
REVOKE ALL ON FUNCTION list_active_practices() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION list_active_practices() TO app_api;

-- Audit hash chain head per tenant (tamper evidence, docs/09-data-model.md). Serialised by an advisory lock in the app.
CREATE OR REPLACE FUNCTION audit_chain_head(p_practice_id uuid)
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT hash FROM "AuditEvent"
  WHERE "practiceId" IS NOT DISTINCT FROM p_practice_id
  ORDER BY id DESC LIMIT 1
$$;
REVOKE ALL ON FUNCTION audit_chain_head(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION audit_chain_head(uuid) TO app_api;
`);

process.stdout.write(out.join("\n") + "\n");
