// Generates docs/06-navigation.md and docs/08-backend-needs.md from spec/ui/*.yaml.
// Run: npm run ui-docs   (validate first)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";
import { loadUi, walkRegions, walkScreen, goTargets, backendOf } from "./ui-lib.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const load = f => yaml.load(fs.readFileSync(path.join(root, "spec", f), "utf8"));
const { modules } = load("modules.yaml");
const { screens: screenList } = load("screens.yaml");
const { roles } = load("roles.yaml");
const screenMeta = Object.fromEntries(screenList.map(s => [s.id, s]));
const ui = loadUi(root);
const moduleOf = {};
modules.forEach(m => m.groups.forEach(g => g.screens.forEach(s => (moduleOf[s] = m.id))));

const HEADER = "<!-- GENERATED by tools/ui-docs.mjs from spec/ui/*.yaml. Do not edit by hand. -->\n\n";
const mid = s => s.replace(/[^A-Za-z0-9]/g, "_");
const label = t => { const [s, v] = t.split("#"); return v ? `${s} › ${v}` : s; };

// ---------- edges ----------
const edges = []; // {from, to, via}
for (const [id, s] of Object.entries(ui.screens))
  for (const item of walkScreen(id, s)) if (item.kind === "el")
    for (const t of [...goTargets(item.el.go), ...(item.el.opens || [])])
      if (t !== "back" && !t.startsWith("external:")) edges.push({ from: item.view ? `${id}#${item.view}` : id, to: t, via: item.el.id });

// ---------- 06-navigation.md ----------
let nav = HEADER + "# Navigation map\n\nEvery navigation edge in the UI spec. Solid arrows: links and buttons (`go`). Views (`#name`) are drawers, modals or panes on their screen. Nodes outside the module are drawn with a dashed border. Global navigation (rail, top bar, chart nav, section tabs, folders) is listed first and omitted from the module diagrams to keep them readable.\n\n";
nav += "## Global navigation\n\n### Left rail by role\n\n| Rail item | " + roles.filter(r => !["patient", "system"].includes(r.id)).map(r => r.name).join(" | ") + " |\n|---|" + roles.filter(r => !["patient", "system"].includes(r.id)).map(() => "---").join("|") + "|\n";
for (const el of ui.nav.rail) {
  const cells = roles.filter(r => !["patient", "system"].includes(r.id)).map(r => {
    if (el.when && el.when.startsWith("role") && !el.when.split(/[ ,]+/).includes(r.id)) return "—";
    const t = typeof el.go === "string" ? el.go : el.go.by_role[r.id];
    return t ? `\`${t}\`` : "—";
  });
  nav += `| ${el.label} | ${cells.join(" | ")} |\n`;
}
const block = (title, items) => `\n### ${title}\n\n` + items.map(el => `- **${el.label || el.id}** → ${[...new Set(goTargets(el.go))].map(t => `\`${t}\``).join(", ") || "_" + (el.does || "no navigation") + "_"}${el.when ? ` _(when ${el.when})_` : ""}`).join("\n") + "\n";
nav += block("Top bar", ui.nav.topbar);
nav += block("Inbox folders", ui.nav["inbox-folders"]);
nav += block("Schedule tabs", ui.nav["schedule-nav"]);
nav += block("Billing tabs", ui.nav["billing-nav"]);
nav += block("Report navigation", ui.nav["report-nav"]);
nav += block("Admin navigation", ui.nav["admin-nav"]);
nav += block("Patients tabs", ui.nav["patients-nav"]);
nav += block("Portal tabs", ui.nav["portal-tabs"]);
nav += `\n### Chart navigation and encounter tabs\n\nEvery chart screen has the chart nav (${ui.patterns.patterns["chart-context"].regions["chart-nav"].length} links to each chart section). Every encounter screen has section tabs: ${ui.patterns.patterns["encounter-workspace"].regions["section-tabs"].map(e => `\`${e.go}\``).join(" → ")}.\n`;
nav += "\n### Rules\n\n" + ui.nav.rules.map(r => `- **${r.id}** ${r.rule}`).join("\n") + "\n";

for (const m of modules) {
  const own = Object.keys(ui.screens).filter(s => moduleOf[s] === m.id);
  const nodes = new Set(); const ext = new Set(); const lines = new Set();
  for (const s of own) { nodes.add(s); Object.keys(ui.screens[s].views || {}).forEach(v => nodes.add(`${s}#${v}`)); }
  for (const e of edges) {
    const fromScreen = e.from.split("#")[0];
    if (!own.includes(fromScreen)) continue;
    if (!nodes.has(e.to)) ext.add(e.to);
    lines.add(`  ${mid(e.from)} --> ${mid(e.to)}`);
  }
  for (const s of own) for (const v of Object.keys(ui.screens[s].views || {})) if (!lines.has(`  ${mid(s)} --> ${mid(`${s}#${v}`)}`)) lines.add(`  ${mid(s)} -.-> ${mid(`${s}#${v}`)}`);
  for (const s of own) if (ui.screens[s].up) { if (!nodes.has(ui.screens[s].up)) ext.add(ui.screens[s].up); }
  let g = "```mermaid\nflowchart LR\n";
  for (const n of nodes) g += `  ${mid(n)}["${label(n)}"]\n`;
  for (const n of ext) g += `  ${mid(n)}["${label(n)}"]:::ext\n`;
  g += [...lines].sort().join("\n") + "\n  classDef ext stroke-dasharray: 4 3,fill:#f4f4f2;\n```\n";
  nav += `\n## ${m.name} (\`${m.id}\`)\n\n${m.intent}\n\n${g}`;
  nav += `\n| Screen | Route | Up | Views | Reached from |\n|---|---|---|---|---|\n`;
  for (const s of own) {
    const sc = ui.screens[s];
    const incoming = [...new Set(edges.filter(e => e.to.split("#")[0] === s && e.from.split("#")[0] !== s).map(e => e.from.split("#")[0]))].sort();
    const globalIn = [...Object.values(ui.nav).filter(Array.isArray).flat(), ...Object.values(ui.patterns.patterns).flatMap(p => Object.values(p.regions || {}).filter(Array.isArray).flat())]
      .some(el => el && goTargets(el.go).includes(s));
    nav += `| \`${s}\` | ${sc.route ? "`" + sc.route + "`" : "_overlay_"} | ${sc.up ? "`" + sc.up + "`" : "—"} | ${Object.keys(sc.views || {}).map(v => "#" + v).join(", ") || "—"} | ${[globalIn ? "global nav" : null, ...incoming.map(x => "`" + x + "`")].filter(Boolean).join(", ") || "—"} |\n`;
  }
}
fs.writeFileSync(path.join(root, "docs", "06-navigation.md"), nav);

// ---------- 08-backend-needs.md ----------
const gloss = fs.readFileSync(path.join(root, "docs", "01-glossary.md"), "utf8");
const ENT = new Set([...gloss.matchAll(/`([A-Z][A-Za-z]+)`/g)].map(m => m[1]).concat(
  "Patient Appointment Encounter Condition Observation DiagnosticReport ServiceRequest MedicationRequest MedicationStatement AllergyIntolerance Immunization Procedure FamilyMemberHistory QuestionnaireResponse Questionnaire Consent Communication CommunicationLog Task DocumentReference Coverage CoverageEligibility Practitioner Location Organization RelatedPerson CarePlan Goal TimeLog CareGap ChargeItem Claim Remittance Payment Adjustment Denial Appeal Authorization AuditEvent Notification WaitlistEntry Recall Estimate Statement PaymentPlan DepositBatch VisitType OrderSet OrderCatalog NoteTemplate SmartPhrase InterfaceStatus User WorkPool AfterVisitSummary ClinicalNote Addendum Specimen Referral PatientList Measure".split(" ")));
const entitiesIn = s => [...new Set((String(s || "").match(/\b[A-Z][A-Za-z]+\b/g) || []).filter(w => ENT.has(w)))];
let be = HEADER + "# Backend needs per screen\n\nWhat each screen needs from the server, derived from `spec/ui`. Use it to map the new UI to existing APIs: for each screen, check that an endpoint provides the **reads**, accepts the **writes**, and enforces the **server logic**. Elements whose need isn't met are hidden behind a capability check, never faked in the client.\n\n- **reads**: entities the screen displays (from `bind`).\n- **writes**: actions that change data (`does`, `tr`).\n- **server logic**: elements marked `be: logic` or that trigger a state transition: rules, matching, checks, external networks. These cannot be built in the UI layer.\n\n";
be += "## Shared by patterns\n\nEvery screen using a pattern also needs what the pattern shows.\n\n";
for (const [pid, pat] of Object.entries(ui.patterns.patterns)) {
  const reads = new Set(); const logic = [];
  for (const item of walkRegions(pat.regions, {})) if (item.kind === "el") {
    entitiesIn(item.el.bind).forEach(e => reads.add(e));
    if (backendOf(item.el) === "logic") logic.push(item.el.id);
  }
  if (reads.size || logic.length) be += `- **${pid}**: reads ${[...reads].sort().join(", ") || "—"}${logic.length ? "; server logic: " + logic.map(x => "`" + x + "`").join(", ") : ""}\n`;
}
be += "\n## Summary\n\n| Module | Screen | Reads | Writes | Server logic |\n|---|---|---|---|---|\n";
const per = {};
for (const [id, s] of Object.entries(ui.screens)) {
  const reads = new Set(); const writes = []; const logic = [];
  for (const item of walkScreen(id, s)) {
    if (item.kind !== "el") continue;
    const el = item.el; const where = (item.view ? `#${item.view}/` : "") + el.id;
    entitiesIn(el.bind).forEach(e => reads.add(e));
    if (el.does || el.tr) writes.push({ where, what: [el.tr ? `\`${el.tr}\`` : null, el.does].filter(Boolean).join(" · ") });
    if (backendOf(el) === "logic") logic.push({ where, what: el.bind || el.does || el.tr || el.label || "" , inv: el.inv || [] });
  }
  per[id] = { reads: [...reads].sort(), writes, logic };
}
for (const m of modules) for (const g of m.groups) for (const id of g.screens) {
  const p = per[id];
  be += `| ${m.name} | \`${id}\` | ${p.reads.length} | ${p.writes.length} | ${p.logic.length} |\n`;
}
for (const m of modules) {
  be += `\n## ${m.name}\n`;
  for (const g of m.groups) for (const id of g.screens) {
    const p = per[id]; const s = ui.screens[id];
    be += `\n### \`${id}\` · ${screenMeta[id].name}\n\n${s.route ? "`" + s.route + "`" : "_overlay_"}${(s.flows || []).length ? " · flows " + s.flows.map(f => "`" + f + "`").join(", ") : ""}\n\n`;
    be += `- **Reads:** ${p.reads.join(", ") || "—"}\n`;
    be += `- **Writes:**${p.writes.length ? "\n" + p.writes.map(w => `  - \`${w.where}\`: ${w.what}`).join("\n") : " —"}\n`;
    be += `- **Server logic:**${p.logic.length ? "\n" + p.logic.map(l => `  - \`${l.where}\`: ${l.what}${l.inv.length ? " (" + l.inv.join(", ") + ")" : ""}`).join("\n") : " —"}\n`;
  }
}
fs.writeFileSync(path.join(root, "docs", "08-backend-needs.md"), be);
console.log(`wrote docs/06-navigation.md (${edges.length} edges) and docs/08-backend-needs.md`);
